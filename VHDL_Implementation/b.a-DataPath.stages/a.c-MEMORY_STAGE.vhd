library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;
use work.myTypes.all;
use work.cpu_32b_types.all;

-- Fetch Stage implementation

entity MEMORY_STAGE is
    generic (
        NBIT : natural := 32;
        NBIT_IDX : natural := 5 -- Number of bits used to select a signle register, also determines the number of registers

    );

    port (
        -- Global
        CLK : in std_logic;
        NRST : in std_logic; -- Reset, activelow
        EN_STAGE : in std_logic; -- Stage enable signal

        -- Memory stage control signals
        MEMORY_CTRL : in mem_ctrl_in_t;

        -- Memory stage, data signals
        MEMORY_DIN : in mem_data_in_t;
        MEMORY_DOUT : out mem_data_out_t;

        -- Data-memory interface, driven by this stage and connected externally
        CPU_MEM_ADDR : buffer std_logic_vector(NBIT - 1 downto 0); -- Buffer needed, since this is also used to do byte addressing for LB
        CPU_DATA_TO_MEM : out std_logic_vector(NBIT - 1 downto 0);
        CPU_DATA_FROM_MEM : in std_logic_vector(NBIT - 1 downto 0);
        CPU_READ_ENABLE : out std_logic;
        CPU_WRITE_ENABLE : out std_logic_vector(3 downto 0)

    );
end MEMORY_STAGE;

architecture STRUCTURAL of MEMORY_STAGE is

    -- Component declarations

    component REG is
        generic (
            NBIT : natural := NBIT
        );
        port (
            D : in std_logic_vector (NBIT - 1 downto 0); -- Input data
            Q : out std_logic_vector (NBIT - 1 downto 0); -- Output data
            CLK, EN, NRST : in std_logic -- Control signals: clock(active high), enable(active high), reset (active low). All are clock synchronous
        );
    end component;

    -- Signals
    signal nrst_final : std_logic; -- NRST signal made by the AND (reset if either the global or control reset signals are active) of the global and control resets
    signal en_lmd : std_logic;

    -- Read operation
    signal byte_from_mem : std_logic_vector (8 - 1 downto 0); -- Byte read from the current DRAM word, yet to be extended
    signal hw_from_mem : std_logic_vector (16 - 1 downto 0); -- Byte read from the current DRAM word, yet to be extended
    signal byte_from_mem_ext, hw_from_mem_ext : std_logic_vector(NBIT - 1 downto 0); -- Sign extended versions of data read from memory
    signal lmd_in : std_logic_vector(NBIT - 1 downto 0); -- Data input of the LMD register, it is the final result of the selection of byte/hw/w and sign extension

    -- Selection for W/HW/B
    signal mem_sel_w_bhw, mem_sel_w_bhw_delayed : std_logic_vector(1 downto 0); -- Signal generated by combining SEL_W and SEL_B_HW from the CU. It is used as the select signal in the final mux to determine if the load should load a word/byte/halfWord
    --  The delayed version is used since the mux selecting if to read a byte/hw/word is not pipelined in other ways, so the selection signal is pipelined and thus delayed by 1 clock cycle                                                                                
    signal mem_addr_delayed : std_logic_vector(NBIT - 1 downto 0); -- This signal needs a 1 clock cycle delay to be in sync with the rest of the memory operations otherwise the address from the yet to be fetched data is used to select the sub indexing (to access a specific byte or half word)
    signal sign_ext_delayed : std_logic;


    -- Write operation
    signal byte_data_to_ram, hw_data_to_ram : std_logic_vector(NBIT - 1 downto 0); -- Signals containging the data to be written (the 8/16 LSBs of ram_data_in are replicated 4/2 times to fill the word)
    signal mem_wen_byte, mem_wen_hw : std_logic_vector(3 downto 0); -- Write enable signals with the right masking applied after the RAM_MODE is recieved from CU. Allow to write a single byute or a single half word to memory
    signal write_enable_pre : std_logic_vector(3 downto 0); -- Write enable with the correct masking for B/HW/W selection, but must be gated through the EN_STAGE and DRAM_WRITE CU flag
    signal write_enable_gate : std_logic; -- and between en_stage and memory_ctrl.wen. Used to gate the write_enable_pre signal with the cu write enable and stage enable
begin
    nrst_final <= NRST and MEMORY_CTRL.NRST_STAGE;
    -----------------------------------------------------------------
    --                      MEMORY STAGE                           --
    -----------------------------------------------------------------
    -- Expose the data-memory request to the external memory system.
    CPU_MEM_ADDR <= MEMORY_DIN.ALU_DATA_IN;
    CPU_READ_ENABLE <= EN_STAGE and MEMORY_CTRL.EN_LMD;
    -- DRAM Moved to execute stage

    -- Selection for load Byte/HalfWord/Word and Signed/Unsigned to LMD
    BYTE_SELECT_MUX : entity work.MUX_41
        generic map(
            NBIT => NBIT/4
        )
        port map(
            D0 => CPU_DATA_FROM_MEM(7 downto 0),
            D1 => CPU_DATA_FROM_MEM(15 downto 8),
            D2 => CPU_DATA_FROM_MEM(23 downto 16),
            D3 => CPU_DATA_FROM_MEM(31 downto 24),
            SEL => mem_addr_delayed(1 downto 0), -- Select the 2 LSBits of the memory address to select the correct byte from the current addres
            Z => byte_from_mem
        );

    HW_SELECT_MUX : entity work.MUX21
        generic map(
            NBIT => NBIT/2
        )
        port map(
            A => CPU_DATA_FROM_MEM(15 downto 0),
            B => CPU_DATA_FROM_MEM(31 downto 16),
            Q => hw_from_mem,
            SEL => mem_addr_delayed(1)
        );

    SIGN_DELAY_FF: entity work.D_FF
     port map(
        D => MEMORY_CTRL.SIGNED_LOAD,
        Q => sign_ext_delayed,
        CLK => CLK,
        EN => EN_STAGE,
        NRST => NRST
    );
    -- Sign extension of the read data
    BYTE_EXTENDER : entity work.BIT_EXT
        generic map(
            NBIT_OUT => NBIT,
            NBIT_IN => 8
        )
        port map(
            D => byte_from_mem,
            ZERO_SIGN_EXT => sign_ext_delayed,
            EXTENDED => byte_from_mem_ext
        );

    HW_EXTENDER : entity work.BIT_EXT
        generic map(
            NBIT_OUT => NBIT,
            NBIT_IN => 16
        )
        port map(
            D => hw_from_mem,
            ZERO_SIGN_EXT => sign_ext_delayed,
            EXTENDED => hw_from_mem_ext
        );

    -- Selection between LW/LB/LHW
    mem_sel_w_bhw(0) <= MEMORY_CTRL.MEM_MODE_B_HW;
    mem_sel_w_bhw(1) <= MEMORY_CTRL.MEM_MODE_W;

    MEM_READ_MODE_PIPELINE : entity work.REG
        generic map(
            NBIT => 2
        )
        port map(
            D => mem_sel_w_bhw,
            Q => mem_sel_w_bhw_delayed,
            CLK => CLK,
            EN => EN_STAGE,
            NRST => NRST
        );

    MEM_LOAD_MODE_MUX : entity work.MUX_41
        generic map(
            NBIT => NBIT
        )
        port map(
            D0 => byte_from_mem_ext,
            D1 => hw_from_mem_ext,
            D2 => CPU_DATA_FROM_MEM,
            D3 => CPU_DATA_FROM_MEM,
            SEL => mem_sel_w_bhw_delayed,
            Z => lmd_in
        );
    -- Write w/hw/b selection mux
    byte_data_to_ram <= MEMORY_DIN.RAM_DATA_IN(7 downto 0) & MEMORY_DIN.RAM_DATA_IN(7 downto 0) & MEMORY_DIN.RAM_DATA_IN(7 downto 0) & MEMORY_DIN.RAM_DATA_IN(7 downto 0); -- Replicate the 8 LSBs across the 32 bits, then use the enable signal to select which one to actually write
    hw_data_to_ram <= MEMORY_DIN.RAM_DATA_IN(15 downto 0) & MEMORY_DIN.RAM_DATA_IN(15 downto 0); -- Same as for byte, but for half word. The write enable vector is what ultimately selects which one is written

    MEM_WRITE_DATA_MUX : entity work.MUX_41
        generic map(
            NBIT => NBIT
        )
        port map(
            D0 => byte_data_to_ram,
            D1 => hw_data_to_ram,
            D2 => MEMORY_DIN.RAM_DATA_IN, -- Otherwise, just write the full 32 bit word
            D3 => MEMORY_DIN.RAM_DATA_IN,
            SEL => mem_sel_w_bhw,
            Z => CPU_DATA_TO_MEM
        );

    -- Write enable signal generation

    --ToDo: Possibly a behavioral implementation is more efficient? But for now use structural for everything
    BYTE_W_EN : entity work.DECODER_41
        port map(
            D0 => mem_wen_byte(0),
            D1 => mem_wen_byte(1),
            D2 => mem_wen_byte(2),
            D3 => mem_wen_byte(3),
            SEL => CPU_MEM_ADDR(1 downto 0)
        );

    HW_W_EN : entity work.DECODER_21
        port map(
            SEL => CPU_MEM_ADDR(1),
            D0 => mem_wen_hw(0),
            D1 => mem_wen_hw(2)
        );
    mem_wen_hw(1) <= mem_wen_hw(0);
    mem_wen_hw(3) <= mem_wen_hw(2);

    -- Write enable source selection
    MEM_WRITE_MODE_MUX : entity work.MUX_41
        generic map(
            NBIT => 4
        )
        port map(
            D0 => mem_wen_byte,
            D1 => mem_wen_hw,
            D2 => (others => '1'),
            D3 => (others => '1'),
            SEL => mem_sel_w_bhw,
            Z => write_enable_pre
        );

    -- Gate the final enable signal through the relevant enables
    write_enable_gate <= EN_STAGE and MEMORY_CTRL.DRAM_WRITE;

    CPU_WRITE_ENABLE_GEN : for i in CPU_WRITE_ENABLE'range generate
        CPU_WRITE_ENABLE(i) <= write_enable_pre(i) and write_enable_gate;
    end generate CPU_WRITE_ENABLE_GEN;

    -- Data propagation to writeback
    en_lmd <= EN_STAGE and MEMORY_CTRL.EN_LMD;

    -- LMD : component REG port map(lmd_in, MEMORY_DOUT.RAM_DATA_OUT, CLK, en_lmd, nrst_final);
    MEMORY_DOUT.RAM_DATA_OUT <= lmd_in; -- Remove the LMD register as it would add an extra clock cycle. The DRAM is syncrhous anyway

    ALU_OUT_REG_MEM : component REG port map(MEMORY_DIN.ALU_DATA_IN, mem_addr_delayed, CLK, EN_STAGE, nrst_final);
    MEMORY_DOUT.ALU_DATA_OUT <= mem_addr_delayed; -- assign the output alu data (which is used as the address, but is now delayed by 1 clock cycle) to the signal used to select the specific byte/hw

    REG_WADDR_PROP_MEM : component REG
        generic map(NBIT => NBIT_IDX)
        port map(MEMORY_DIN.RD_ADDR_IN, MEMORY_DOUT.RD_ADDR_OUT, CLK, EN_STAGE, nrst_final);
    end;
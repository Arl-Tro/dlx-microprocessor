library IEEE;
use IEEE.std_logic_1164.all;
use IEEE.numeric_std.all;
use WORK.constants.all;

entity data_mem_arbiter is
    generic (
        ADDR_BUS_SIZE : integer := NumBit; -- width of memory address bus (32 bit)
        DATA_BUS_SIZE : integer := NumBit -- width of memory data bus (32 bit)
    );
    port (
        -- control signals from WRF
        SPILL : in std_logic;
        FILL : in std_logic;

        -- interface from WRF (Spill/Fill operations)
        WRF_MEM_ADDR : in std_logic_vector(ADDR_BUS_SIZE - 1 downto 0);
        WRF_DATA_TO_MEM : in std_logic_vector(DATA_BUS_SIZE - 1 downto 0);
        WRF_DATA_FROM_MEM : out std_logic_vector(DATA_BUS_SIZE - 1 downto 0);

        -- interface from Pipeline EX/MEM Stage ( Load/Store operations)
        CPU_MEM_ADDR : in std_logic_vector(ADDR_BUS_SIZE - 1 downto 0);
        CPU_DATA_TO_MEM : in std_logic_vector(DATA_BUS_SIZE - 1 downto 0);
        CPU_DATA_FROM_MEM : out std_logic_vector(DATA_BUS_SIZE - 1 downto 0);
        CPU_READ_ENABLE : in std_logic; -- generated by CU for Load (LW)
        CPU_WRITE_ENABLE : in std_logic_vector(3 downto 0); -- generated by CU for Store (SW)

        -- physical data RAM bus outputs/inputs
        RAM_ADDR : out std_logic_vector(ADDR_BUS_SIZE - 1 downto 0);
        RAM_DATA_TO_MEM : out std_logic_vector(DATA_BUS_SIZE - 1 downto 0);
        RAM_DATA_FROM_MEM : in std_logic_vector(DATA_BUS_SIZE - 1 downto 0);
        RAM_READ_ENABLE : out std_logic;
        RAM_WRITE_ENABLE : out std_logic_vector(3 downto 0)
    );
end data_mem_arbiter;

architecture behavioral of data_mem_arbiter is
begin

    -- pure ombinational multiplexer process
    ARBITER_PROC : process (
        SPILL, FILL,
        WRF_MEM_ADDR, WRF_DATA_TO_MEM,
        CPU_MEM_ADDR, CPU_DATA_TO_MEM, CPU_READ_ENABLE, CPU_WRITE_ENABLE,
        RAM_DATA_FROM_MEM
        )
    begin
        if (SPILL = '1') then

            -- SPILL MODE: saving register window to Data RAM (Stack Write)
            RAM_ADDR <= WRF_MEM_ADDR;
            RAM_DATA_TO_MEM <= WRF_DATA_TO_MEM;
            RAM_WRITE_ENABLE <= (others => '1');
            RAM_READ_ENABLE <= '0';

            -- disconnect outputs to CPU/WRF read channels
            CPU_DATA_FROM_MEM <= (others => '0');
            WRF_DATA_FROM_MEM <= (others => '0');

        elsif (FILL = '1') then

            -- FILL MODE: restoring register window from Data RAM (Stack Read)
            RAM_ADDR <= WRF_MEM_ADDR;
            RAM_DATA_TO_MEM <= (others => '0');
            RAM_WRITE_ENABLE <= (others => '0');
            RAM_READ_ENABLE <= '1';

            -- route memory output directly to WRF
            WRF_DATA_FROM_MEM <= RAM_DATA_FROM_MEM;
            CPU_DATA_FROM_MEM <= (others => '0');

        else

            -- NORMAL MODE: pipeline executing Load/Store instructions
            RAM_ADDR <= CPU_MEM_ADDR;
            RAM_DATA_TO_MEM <= CPU_DATA_TO_MEM;
            RAM_WRITE_ENABLE <= CPU_WRITE_ENABLE;
            RAM_READ_ENABLE <= CPU_READ_ENABLE;

            -- route memory output directly to CPU WB Stage
            CPU_DATA_FROM_MEM <= RAM_DATA_FROM_MEM;
            WRF_DATA_FROM_MEM <= (others => '0');

        end if;
    end process ARBITER_PROC;

end behavioral;
library ieee;
use ieee.std_logic_1164.all;
use work.myTypes.all;
use work.cpu_32b_types.all;

entity DLX is
  generic (
    IR_SIZE : integer := 32; -- Instruction Register Size
    PC_SIZE : integer := 32 -- Program Counter Size
  ); -- ALU_OPC_SIZE if explicit ALU Op Code Word Size
  port (
    Clk : in std_logic;
    Rst : in std_logic); -- Active Low
end DLX;

-- This architecture is currently not complete
-- it just includes:
-- instruction register (complete)
-- program counter (complete)
-- instruction ram memory (complete)
-- control unit (UNCOMPLETE)
--
architecture dlx_rtl of DLX is

  --------------------------------------------------------------------
  -- Components Declaration
  --------------------------------------------------------------------

  -- Datapath
  component DATAPATH_DBG is
    generic (
      NBIT : natural := 32;
      NBIT_IDX : natural := 5 -- Number of bits used to select a signle register, also determines the number of registers
    );
    port (
      -- Global
      CLK : in std_logic;
      NRST : in std_logic; -- Reset, activelow

      -- Fetch stage interface
      FETCH_CTRL : in if_ctrl_in_t;
      -- Decode stage interface
      DECODE_CTRL : in id_ctrl_in_t;
      -- Execute stage interface
      EXECUTE_CTRL : in ex_ctrl_in_t;
      -- Memory stage interface
      MEMORY_CTRL : in mem_ctrl_in_t;
      -- Writeback stage interface
      WRITEBACK_CTRL : in wb_ctrl_in_t;

      -- Top-level observation
      IR_TO_CU : out std_logic_vector(NBIT - 1 downto 0);
      BRANCH : out std_logic; -- Will be 1 if a branch should be taken or 0 otherwise
      STALL : buffer std_logic -- STALL signal as generated by the hazard unit

    );
  end component;

  -- Control Unit
  component dlx_cu
    generic (
      MICROCODE_MEM_SIZE : integer := 64; -- Microcode Memory Size
      FUNC_SIZE : integer := 11; -- Func Field Size for R-Type Ops
      OP_CODE_SIZE : integer := 6; -- Op Code Size
      --ALU_OPC_SIZE       :     integer := 6;  -- ALU Op Code Word Size
      IR_SIZE : integer := 32; -- Instruction Register Size    
      CW_SIZE : integer := 17); -- Control Word Size
    port (
      Clk : in std_logic; -- Clock
      Rst : in std_logic; -- Reset:Active-Low
      -- Instruction Register
      IR_IN : in std_logic_vector(IR_SIZE - 1 downto 0);
      BRANCH : in std_logic;
      STALL : in std_logic; -- Stall signal generated by the hazard unit, required to reset control words
      -- Fetch stage interface
      FETCH_CTRL : out if_ctrl_in_t;
      -- Decode stage outerface
      DECODE_CTRL : out id_ctrl_in_t;
      -- Execute stage interface
      EXECUTE_CTRL : out ex_ctrl_in_t;
      -- Memory stage interface
      MEMORY_CTRL : out mem_ctrl_in_t;
      -- Writeback stage interface
      WRITEBACK_CTRL : out wb_ctrl_in_t
    );
  end component;
  ----------------------------------------------------------------
  -- Signals Declaration
  ----------------------------------------------------------------
  signal IR : std_logic_vector(IR_SIZE - 1 downto 0);
  signal branch_i, stall_i : std_logic;

  -- Control Unit signals

  signal fetch_ctrl_i : if_ctrl_in_t;
  signal decode_ctrl_i : id_ctrl_in_t;
  signal execute_ctrl_i : ex_ctrl_in_t;
  signal memory_ctrl_i : mem_ctrl_in_t;
  signal writeback_ctrl_i : wb_ctrl_in_t;

begin -- DLX
  -- Control Unit Instantiation
  CU_I : dlx_cu
  port map(
    Clk => Clk,
    Rst => Rst,
    IR_IN => IR,
    BRANCH => branch_i,
    STALL => stall_i,

    -- Fetch stage interface
    FETCH_CTRL => fetch_ctrl_i,
    -- Decode stage interface
    DECODE_CTRL => decode_ctrl_i,
    -- Execute stage interface
    EXECUTE_CTRL => execute_ctrl_i,
    -- Memory stage interface
    MEMORY_CTRL => memory_ctrl_i,
    -- Writeback stage interface
    WRITEBACK_CTRL => writeback_ctrl_i

  );

  -- Datapath Instantiation
  DP_I : DATAPATH_DBG
  port map(
    -- Global
    CLK => Clk,
    NRST => Rst,
    BRANCH => branch_i,
    STALL => stall_i,

    IR_TO_CU => IR,
    -- Fetch stage interface
    FETCH_CTRL => fetch_ctrl_i,
    -- Decode stage interface
    DECODE_CTRL => decode_ctrl_i,
    -- Execute stage interface
    EXECUTE_CTRL => execute_ctrl_i,
    -- Memory stage interface
    MEMORY_CTRL => memory_ctrl_i,
    -- Writeback stage interface
    WRITEBACK_CTRL => writeback_ctrl_i
  );

end dlx_rtl;
			A => A_tb((i + 1) * delta - 1 downto i * delta),
			B => B_tb((i + 1) * delta - 1 downto i * delta),
			Ci => Co_rca(i),
			S => open,
			Co => Co_rca(i + 1)
		);
	end generate;

